from copy import deepcopy
from pathlib import Path
from typing import Any

from pyrpckit.codegen import (
    generate_typescript_client,
    render_typescript_client,
)
from pyrpckit.codegen.typescript import TypeScriptClientOptions


def options() -> TypeScriptClientOptions:
    return TypeScriptClientOptions(
        client_name="GreetingClient",
        source="greeting.openrpc.json",
    )


def test_the_generated_package_has_one_module_per_concern(
    document: dict[str, Any],
) -> None:
    files = render_typescript_client(document, options())

    assert set(files) == {"models.ts", "client.ts", "index.ts"}
    assert all(
        content.startswith(
            "// Generated by pyrpckit from greeting.openrpc.json.\n"
            "// Do not edit this file manually.\n"
        )
        for content in files.values()
    )


def test_renders_typed_methods_namespaces_and_notifications(
    document: dict[str, Any],
) -> None:
    files = render_typescript_client(document, options())
    client = files["client.ts"]

    assert "class GreetingNamespaceClient {" in client
    assert "export class GreetingClient {" in client
    assert "readonly greeting;" in client
    assert "say(params: SayParams): Promise<SayResult>" in client
    assert "async forget(params: ForgetParams): Promise<void>" in client
    assert "greeted(): Promise<GreetedResult>" in client
    assert "async clear(): Promise<void>" in client
    assert "AsyncIterable<GreetingChangedNotification>" in client
    assert 'import type { RpcTransport } from "../transport";' in client


def test_renders_models_as_types_and_literal_unions(
    document: dict[str, Any],
) -> None:
    document_with_enum = deepcopy(document)
    inline_enum = document_with_enum["components"]["schemas"]["SayParams"][
        "properties"
    ]["name"]
    inline_enum["enum"] = ["Ada", "Grace"]
    models = render_typescript_client(document_with_enum, options())["models.ts"]

    assert 'name: "Ada" | "Grace";' in models
    assert "export type GreetingEvent = GreetingSaid | GreetingForgotten;" in models
    assert 'GREETING_SAY: "greeting.say",' in models


def test_transport_module_can_be_configured(document: dict[str, Any]) -> None:
    configured = TypeScriptClientOptions(transport_module="@example/rpc")

    client = render_typescript_client(document, configured)["client.ts"]

    assert 'import type { RpcTransport } from "@example/rpc";' in client


def test_writing_is_idempotent_and_check_does_not_write(
    document: dict[str, Any],
    tmp_path: Path,
) -> None:
    output = tmp_path / "generated"

    assert len(generate_typescript_client(document, output, options())) == 3
    assert generate_typescript_client(document, output, options()) == ()
    (output / "client.ts").write_text("stale\n", encoding="utf-8")

    assert generate_typescript_client(document, output, options(), check=True) == (
        output / "client.ts",
    )
    assert (output / "client.ts").read_text(encoding="utf-8") == "stale\n"
