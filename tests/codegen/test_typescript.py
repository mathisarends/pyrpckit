def test_writing_is_idempotent_and_check_does_not_write(
    document: dict[str, Any],
    tmp_path: Path,
) -> None:
    output = tmp_path / "generated"

    assert len(generate_typescript_client(document, output, options())) == 9
    assert generate_typescript_client(document, output, options()) == ()
    (output / "client.ts").write_text("stale\n", encoding="utf-8")

    assert generate_typescript_client(document, output, options(), check=True) == (
        output / "client.ts",
    )
    assert (output / "client.ts").read_text(encoding="utf-8") == "stale\n"


def test_generated_typescript_is_prettier_formatted(
    document: dict[str, Any],
    tmp_path: Path,
) -> None:
    output = tmp_path / "generated"
    generate_typescript_client(document, output, options())
    prettier = shutil.which("npx.cmd") or shutil.which("npx")
    if prettier is None:
        pytest.skip("npx is not installed")

    formatting = subprocess.run(
        [prettier, "prettier", "--check", str(output)],
        capture_output=True,
        text=True,
        check=False,
    )

    assert formatting.returncode == 0, formatting.stdout + formatting.stderr
