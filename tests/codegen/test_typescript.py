def test_api_root_and_names_are_shared_with_the_python_layout(
    document: dict[str, Any],
) -> None:
    nested = deepcopy(document)
    nested["methods"][0]["name"] = "browser.nav.navigate"
    nested["methods"] = [nested["methods"][0]]
    configured = TypeScriptClientOptions(
        client_name="BrowserControlClient",
        api_root="browser",
        api_names={"nav": "navigation"},
    )

    files = render_typescript_client(nested, configured)

    assert "api/navigation.ts" in files
    assert "export class NavigationApi" in files["api/navigation.ts"]
    assert "readonly navigation: NavigationApi;" in files["client.ts"]
    assert 'method: "browser.nav.navigate"' in files["metadata.ts"]


def test_all_optional_params_default_to_an_empty_object(
    document: dict[str, Any],
) -> None:
    optional = deepcopy(document)
    optional["methods"][0]["params"][0]["required"] = False
