import shutil
import subprocess
from copy import deepcopy
from pathlib import Path
from typing import Any

import pytest

from pyrpckit.codegen import generate_typescript_client, render_typescript_client
from pyrpckit.codegen.typescript import TypeScriptClientOptions


def options() -> TypeScriptClientOptions:
    return TypeScriptClientOptions(
        client_name="GreetingClient",
        source="greeting.openrpc.json",
    )


def test_the_generated_package_has_one_module_per_concern(
    document: dict[str, Any],
) -> None:
    files = render_typescript_client(document, options())

    assert set(files) == {
        ".pyrpckit-generated.json",
        "core.ts",
        "api/greeting.ts",
        "api/index.ts",
        "client.ts",
        "errors.ts",
        "index.ts",
        "metadata.ts",
        "models.ts",
    }
    assert all(
        content.startswith(
            "// Generated by pyrpckit from greeting.openrpc.json.\n"
            "// Do not edit this file manually.\n"
            "// Regenerate it from the OpenRPC document instead.\n"
        )
        for name, content in files.items()
        if name != ".pyrpckit-generated.json"
    )


def test_renders_typed_api_groups_and_events(document: dict[str, Any]) -> None:
    files = render_typescript_client(document, options())
    api = files["api/greeting.ts"]
    client = files["client.ts"]

    assert "export class GreetingApi {" in api
    assert "say(params: SayParams): Promise<SayResult>" in api
    assert "async forget(params: ForgetParams): Promise<void>" in api
    assert "greeted(): Promise<GreetedResult>" in api
    assert "readonly greeting: GreetingApi;" in client
    assert "events(): AsyncIterable<GreetingEvent>" in client
    assert "notifications()" not in client


def test_renders_models_as_types_and_literal_unions(
    document: dict[str, Any],
) -> None:
    document_with_enum = deepcopy(document)
    inline_enum = document_with_enum["components"]["schemas"]["SayParams"][
        "properties"
    ]["name"]
    inline_enum["enum"] = ["Ada", "Grace"]

    models = render_typescript_client(document_with_enum, options())["models.ts"]

    assert 'name: "Ada" | "Grace";' in models
    assert "export type GreetingEvent = GreetingSaid | GreetingForgotten;" in models
    assert 'type: "greeting.said";' in models


