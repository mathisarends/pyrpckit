def test_python_name_collisions_fail_with_both_wire_names(
    document: dict[str, Any],
    options: PythonClientOptions,
) -> None:
    collision = deepcopy(document)
    first = collision["methods"][0]
    second = deepcopy(first)
    first["name"] = "greeting.open-tab"
    second["name"] = "greeting.openTab"
    collision["methods"] = [first, second]

    with pytest.raises(UnsupportedSchemaError, match="greeting.open-tab") as error:
        render_python_client(collision, options)

    assert "greeting.openTab" in str(error.value)
    assert "open_tab" in str(error.value)


def test_writing_is_idempotent_and_check_does_not_write(
    document: dict[str, Any],
    options: PythonClientOptions,
    tmp_path: Path,
) -> None:
    output = tmp_path / PACKAGE

    assert len(generate_python_client(document, output, options)) == 13
    assert generate_python_client(document, output, options) == ()
    (output / "client.py").write_text("stale\n", encoding="utf-8")

    assert generate_python_client(document, output, options, check=True) == (
        output / "client.py",
    )
    assert (output / "client.py").read_text(encoding="utf-8") == "stale\n"


def test_generated_python_is_ruff_formatted(
    document: dict[str, Any],
    options: PythonClientOptions,
    tmp_path: Path,
) -> None:
    output = tmp_path / PACKAGE
    generate_python_client(document, output, options)
    (tmp_path / "pyproject.toml").write_text(
        '[tool.ruff]\nline-length = 88\n[tool.ruff.lint]\nselect = ["E", "F", "I"]\n'
        f'[tool.ruff.lint.isort]\nknown-first-party = ["{PACKAGE}"]\n',
        encoding="utf-8",
    )

    lint = subprocess.run(
        [sys.executable, "-m", "ruff", "check", str(output)],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )
    formatting = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--check", str(output)],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )

    assert lint.returncode == 0, lint.stdout + lint.stderr
    assert formatting.returncode == 0, formatting.stdout + formatting.stderr
