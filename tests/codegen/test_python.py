def test_optional_nullable_params_use_unset_instead_of_dropping_none(
    document: dict[str, Any],
    options: PythonClientOptions,
) -> None:
    optional = deepcopy(document)
    schema = {"anyOf": [{"type": "string"}, {"type": "null"}]}
    optional["methods"][0]["params"] = [
        {"name": "title", "required": False, "schema": schema}
    ]
    params = optional["components"]["schemas"]["SayParams"]
    params["properties"] = {"title": schema}
    params["required"] = []

    api = render_python_client(optional, options)["api/greeting.py"]

    assert "title: str | None | UnsetType = UNSET" in api
    assert "if title is not UNSET:" in api
    assert 'values["title"] = title' in api
    assert "exclude_unset=True" in api
    assert "exclude_none" not in api


